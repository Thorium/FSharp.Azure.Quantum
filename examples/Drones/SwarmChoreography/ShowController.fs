/// The show controller a scale run ships with its trajectories: an F# script that flies
/// `trajectories/DroneN.csv` in GUIDED mode on ArduCopter, every drone a position
/// setpoint at 10 Hz along the common progress law, against ArduPilot SITL or real links.
/// The MAVLink link code is the shared launcher's (MavlinkMission.FsxScript); the flight
/// is streamed, not uploaded, because waypoint missions cannot fly legs of different
/// lengths together.
module FSharp.Azure.Quantum.Examples.Drones.SwarmChoreography.ShowController

open System.IO

let private template =
    """
// show_controller.fsx - generated by FSharp.Azure.Quantum (SwarmChoreography scale run).
//
// Flies the timed trajectories in trajectories/DroneN.csv on ArduCopter 4.7 over
// MAVLink 2, in GUIDED mode: every drone gets its planned position (and velocity) at
// 10 Hz along the show's common progress law, so the drones move together exactly as
// the plan was checked. TRY IT AGAINST ARDUPILOT SITL BEFORE ANY REAL AIRCRAFT.
//
//   dotnet fsi show_controller.fsx --dry-run     reads the files, prints every drone's
//                                                start slot and the SITL commands; no network
//   dotnet fsi show_controller.fsx               connects and flies
//   dotnet fsi show_controller.fsx --speedup N   against SITL run at N x real time
//   dotnet fsi show_controller.fsx --check       closest approach in telemetry.csv of a
//                                                flight, against the plan; no network
//
// SITL instance i serves tcp:127.0.0.1:(5760 + 10 i); sitl_start.sh starts one per
// drone at its own slot. Per vehicle the controller waits for its heartbeat and a
// position fix, checks it is a copter standing on its slot, sets GUIDED, arms, takes
// off to the take-off height, and once every vehicle is up starts the show clock. It
// writes telemetry.csv (show seconds, drone, x, y, z in the show's frame) and lands
// every drone where it is when the show ends, or on Ctrl+C.
//
// MAVLink library: the NuGet package "MAVLink" (ArduPilot Mission Planner's generated
// C# MAVLink, https://github.com/ArduPilot/MissionPlanner/tree/master/ExtLibs/Mavlink).

#r "nuget: MAVLink, 1.0.8"

open System
open System.Collections.Concurrent
open System.Globalization
open System.IO
open System.Net.Sockets
open System.Text.Json
open System.Threading

type MsgId = MAVLink.MAVLINK_MSG_ID

let dir = __SOURCE_DIRECTORY__
let dryRun = fsi.CommandLineArgs |> Array.contains "--dry-run"
let checkOnly = fsi.CommandLineArgs |> Array.contains "--check"

/// SITL only: the simulation runs this many times faster than the wall clock.
let speedup =
    match fsi.CommandLineArgs |> Array.tryFindIndex ((=) "--speedup") with
    | Some i when i + 1 < fsi.CommandLineArgs.Length -> max 1.0 (float fsi.CommandLineArgs.[i + 1])
    | _ -> 1.0

/// Height (m) every drone takes off to before the show clock starts. The plan's ground
/// slots are at 0, which a copter cannot hold in the air, so every ground keyframe is
/// flown at this height: the same offset for every drone, which keeps the drones'
/// relative positions, and so the plan's separation, exactly. The show ends with a
/// landing from it.
let takeoffM = 2.0

/// How far (m) a vehicle may stand from its slot before it is flown.
let slotToleranceM = 2.0

/// How long (s) a vehicle may keep refusing to arm before nobody flies.
let armWaitS = 90.0

let invariant = CultureInfo.InvariantCulture
let number (s: string) = Double.Parse(s, invariant)

// =============================================================================
// THE PLAN
// =============================================================================

let show = JsonDocument.Parse(File.ReadAllText(Path.Combine(dir, "show.json"))).RootElement
let drones = show.GetProperty("drones").GetInt32()
let durationS = show.GetProperty("duration_s").GetDouble()
let plannedClosest = show.GetProperty("closest_approach_m").GetDouble()

let origin =
    let o = [| for v in show.GetProperty("origin").EnumerateArray() -> v.GetDouble() |]
    if o.Length = 3 then Some(o.[0], o.[1], o.[2]) else None

/// A drone's keyframes: show second, position (x east, y north, z up, metres).
let keyframes (d: int) =
    File.ReadAllLines(Path.Combine(dir, "trajectories", sprintf "Drone%d.csv" d))
    |> Array.skip 1
    |> Array.map (fun line ->
        let f = line.Split(',')
        let z = number f.[3]
        number f.[0], (number f.[1], number f.[2], (if z < 1e-9 then takeoffM else z)))

let plan = Array.init drones keyframes

/// Progress through a move at share f of its time: the smoothstep, and its rate.
let progress (f: float) = f * f * (3.0 - 2.0 * f)
let progressRate (f: float) = 6.0 * f * (1.0 - f)

/// Where drone d is at show second t, and its velocity, from its keyframes: held at a
/// keyframe's position between arrival and departure, on the straight line between a
/// departure and the next arrival otherwise.
let planned (d: int) (t: float) =
    let k = plan.[d]

    if t <= fst k.[0] then
        snd k.[0], (0.0, 0.0, 0.0)
    elif t >= fst k.[k.Length - 1] then
        snd k.[k.Length - 1], (0.0, 0.0, 0.0)
    else
        let i = k |> Array.findIndex (fun (ti, _) -> ti > t)
        let t0, (x0, y0, z0) = k.[i - 1]
        let t1, (x1, y1, z1) = k.[i]

        if t1 - t0 <= 1e-9 || (x0 = x1 && y0 = y1 && z0 = z1) then
            (x0, y0, z0), (0.0, 0.0, 0.0)
        else
            let f = (t - t0) / (t1 - t0)
            let s = progress f
            let rate = progressRate f / (t1 - t0)
            (x0 + s * (x1 - x0), y0 + s * (y1 - y0), z0 + s * (z1 - z0)),
            (rate * (x1 - x0), rate * (y1 - y0), rate * (z1 - z0))

/// Each drone's slot on the ground: its first keyframe (at the take-off height here).
let slots = plan |> Array.map (fun k -> snd k.[0])

/// A slot's latitude and longitude from the origin (equirectangular, as the exporter).
let geo (x: float, y: float) =
    match origin with
    | Some(lat, lon, _) ->
        let latD = lat + y / 111320.0
        let lonD = lon + x / (111320.0 * Math.Cos(lat * Math.PI / 180.0))
        Some(latD, lonD)
    | None -> None

let distanceM (lat1: float) (lon1: float) (lat2: float) (lon2: float) =
    let r = 6371000.0
    let dLat = (lat2 - lat1) * Math.PI / 180.0
    let dLon = (lon2 - lon1) * Math.PI / 180.0 * Math.Cos(lat1 * Math.PI / 180.0)
    r * Math.Sqrt(dLat * dLat + dLon * dLon)

printfn "%d drones, %.0f s of show, planned closest approach %.2f m" drones durationS plannedClosest

if dryRun then
    printfn ""
    printfn "Start one ArduCopter SITL per drone at its slot (or run sitl_start.sh):"

    for d in 0 .. drones - 1 do
        match geo (let (x, y, _) = slots.[d] in (x, y)) with
        | Some(lat, lon) ->
            printfn
                "  arducopter --model + --defaults copter.parm -w -I%d --home %.7f,%.7f,%.1f,0"
                d
                lat
                lon
                (match origin with Some(_, _, alt) -> alt | None -> 0.0)
        | None ->
            let x, y, _ = slots.[d]
            printfn "  Drone%d at x %.2f m, y %.2f m (no origin: run the example with --home-lat/--home-lon)" d x y

    printfn ""
    printfn "Then: dotnet fsi show_controller.fsx [--speedup N]"
    exit 0

// =============================================================================
// CHECK: the flight against the plan
// =============================================================================

/// Closest two drones come in telemetry.csv (show seconds, drone, x, y, z), sampled on a
/// common 0.1 s grid; pairs both under 0.5 m are on the ground and skipped.
let closestFlown () =
    let rows =
        File.ReadAllLines(Path.Combine(dir, "telemetry.csv"))
        |> Array.skip 1
        |> Array.map (fun l -> let f = l.Split(',') in number f.[0], int f.[1], (number f.[2], number f.[3], number f.[4]))

    let byDrone = Array.init drones (fun d -> rows |> Array.filter (fun (_, i, _) -> i = d) |> Array.map (fun (t, _, p) -> t, p))
    let tEnd = rows |> Array.map (fun (t, _, _) -> t) |> Array.max
    let cursors = Array.zeroCreate<int> drones
    let here = Array.zeroCreate<float * float * float> drones
    let mutable best = (Double.PositiveInfinity, 0.0, -1, -1)

    for t in 0.0 .. 0.1 .. tEnd do
        for d in 0 .. drones - 1 do
            let s = byDrone.[d]

            if s.Length > 0 then
                while cursors.[d] < s.Length && fst s.[cursors.[d]] < t do
                    cursors.[d] <- cursors.[d] + 1

                here.[d] <-
                    if cursors.[d] >= s.Length then snd s.[s.Length - 1]
                    elif cursors.[d] = 0 then snd s.[0]
                    else
                        let t0, (x0, y0, z0) = s.[cursors.[d] - 1]
                        let t1, (x1, y1, z1) = s.[cursors.[d]]
                        let f = if t1 > t0 then (t - t0) / (t1 - t0) else 1.0
                        x0 + f * (x1 - x0), y0 + f * (y1 - y0), z0 + f * (z1 - z0)

        for i in 0 .. drones - 1 do
            for j in i + 1 .. drones - 1 do
                if byDrone.[i].Length > 0 && byDrone.[j].Length > 0 then
                    let (ax, ay, az), (bx, by, bz) = here.[i], here.[j]

                    if az >= 0.5 || bz >= 0.5 then
                        let dist = Math.Sqrt((ax - bx) ** 2.0 + (ay - by) ** 2.0 + (az - bz) ** 2.0)
                        let (bd, _, _, _) = best
                        if dist < bd then best <- (dist, t, i, j)

    best

if checkOnly then
    let dist, t, i, j = closestFlown ()
    printfn "flown: closest approach %.2f m at %.1f s, Drone%d and Drone%d; planned %.2f m" dist t i j plannedClosest
    exit (if dist >= plannedClosest * 0.5 then 0 else 1)

